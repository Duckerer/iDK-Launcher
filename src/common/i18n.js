const dict = { en, ru };

function resolve(lang, key, params) {
  let s = (dict[lang] && dict[lang][key]) || dict.en[key] || key;
  if (params) {
    for (const k in params) s = s.replace('{' + k + '}', String(params[k]));
  }
  return s;
}

if (typeof window !== 'undefined') {
  let currentLang = 'en';
  window.__setLang = (l) => {
    currentLang = dict[l] ? l : 'en';
  };
  window.__getLang = () => currentLang;
  window.t = (key, params) => resolve(currentLang, key, params);
  window.__DICT = dict;
} else {
  const de = require('./lang/de');
  const fr = require('./lang/fr');
  const es = require('./lang/es');
  const it = require('./lang/it');
  const pl = require('./lang/pl');
  const uk = require('./lang/uk');
  Object.assign(dict, { de, fr, es, it, pl, uk });
  module.exports = { resolve, en, ru, dict };
}
